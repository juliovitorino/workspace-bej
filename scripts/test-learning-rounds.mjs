import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { transpileModule } from 'typescript';
const memory = new Map([['bej-study-v2:history', 'preserve']]);
globalThis.localStorage = { getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value) };
let notifications = 0;
globalThis.window = { dispatchEvent() { notifications++; } };
globalThis.Event = class { constructor(type) { this.type = type; } };
const module = { exports: {} };
new Function('module', 'exports', transpileModule(readFileSync('src/utils/learningRound.ts', 'utf8'), { compilerOptions: { module: 1, target: 9 } }).outputText)(module, module.exports);
const { roundKey, readRound, presentItem, finishRound, reconcileRound } = module.exports;
const ids = Array.from({ length: 528 }, (_, i) => `intention-${i}`);
const key = roundKey('en-US', 'chunk-flashcards');
for (const id of ids.slice(0, 50)) presentItem(key, ids, id);
assert.equal(readRound(key).presentedItemIds.length, 50);
assert.equal(ids.filter(id => !readRound(key).presentedItemIds.includes(id)).length, 478);
// Esgotar um nível não pode reiniciar a rodada com itens de outros níveis pendentes.
finishRound(key, ids.slice(0, 50), ids);
assert.equal(readRound(key).round, 1);
assert.equal(readRound(key).presentedItemIds.length, 50);
for (const id of ids.slice(50)) presentItem(key, ids, id);
assert.equal(readRound(key).round, 1);
finishRound(key, ids.slice(0, 50), ids);
assert.equal(readRound(key).round, 2);
assert.equal(readRound(key).completedRounds, 1);
assert.equal(readRound(key).presentedItemIds.length, 0);
finishRound(key, ids, ids); assert.equal(readRound(key).round, 2);
presentItem(key, ids, ids[0]); presentItem(key, ids, ids[0]);
assert.equal(readRound(key).presentedItemIds.length, 1);
const changed = [...ids.slice(1), 'added'];
assert.equal(reconcileRound(key, changed).presentedItemIds.length, 0);
presentItem(key, changed, 'added');
assert.deepEqual(readRound(key).presentedItemIds, ['added']);
finishRound(key, [], changed); assert.equal(readRound(key).round, 2);
const favorites = roundKey('en-US', 'favorite-chunks');
const spanish = roundKey('es-ES', 'chunk-flashcards');
const mixed = ['intention:parent', 'example:parent:uuid'];
for (const id of mixed) presentItem(favorites, mixed, id);
assert.equal(readRound(favorites).presentedItemIds.length, 2);
finishRound(favorites, mixed); assert.equal(readRound(favorites).round, 2);
assert.equal(readRound(spanish).round, 1); assert.equal(readRound(key).round, 2);
assert.equal(memory.get('bej-study-v2:history'), 'preserve');
assert.ok(notifications > 0);
memory.set(key, 'invalid'); assert.throws(() => readRound(key));
console.log('PASS: 528 itens, mudança de nível, reinício após catálogo completo, favoritos, persistência, deduplicação e isolamento.');
